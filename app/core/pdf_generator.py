"""
SevaPath English PDF Report Generator.

Generates professional, accessible, and tamper-evident citizen preparation reports
using ReportLab with standard ASCII-safe typography and clear disclaimers.
"""

import io
from datetime import datetime, timezone
from typing import Dict, Any, List

from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable


def build_preparation_pdf(
    service_data: Dict[str, Any],
    progress_data: Dict[str, Any],
    requirements_data: List[Dict[str, Any]]
) -> bytes:
    """
    Builds a complete, printable preparation checklist PDF for a civic service.

    Security & Privacy:
    - Never includes session tokens, cookie hashes, or personal identifying data.
    - Uses ISO currency format 'INR 60' and 'INR 0' for standard ASCII compatibility.
    - Embeds unambiguous statutory preparation disclaimers.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    # Custom professional styles
    primary_color = colors.HexColor("#1A365D")
    secondary_color = colors.HexColor("#2B6CB0")
    dark_text = colors.HexColor("#2D3748")
    muted_text = colors.HexColor("#718096")
    success_color = colors.HexColor("#22543D")
    success_bg = colors.HexColor("#C6F6D5")
    warning_color = colors.HexColor("#744210")
    warning_bg = colors.HexColor("#FEEBC8")

    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=primary_color,
        spaceAfter=4
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=15,
        textColor=muted_text,
        spaceAfter=12
    )

    h2_style = ParagraphStyle(
        "Heading2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=primary_color,
        spaceBefore=12,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=dark_text
    )

    body_bold = ParagraphStyle(
        "BodyDarkBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=13,
        textColor=dark_text
    )

    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#4A5568")
    )

    elements = []

    # 1. Header & Branding
    elements.append(Paragraph("SevaPath — Citizen Preparation Checklist", subtitle_style))
    service_name = service_data.get("name", "Public Service")
    service_slug = service_data.get("slug", "")

    # Extract service code
    code_map = {
        "community-certificate": "REV-101",
        "nativity-certificate": "REV-102",
        "income-certificate": "REV-103",
    }
    service_code = code_map.get(service_slug, "REV-eSevai")

    elements.append(Paragraph(f"{service_name} [{service_code}]", title_style))
    elements.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceBefore=4, spaceAfter=10))

    # Top Statutory Disclaimer
    disclaimer_text = (
        "<b>OFFICIAL NOTICE:</b> This document is an offline preparation checklist generated by SevaPath "
        "to assist citizens in organizing requirements prior to visiting an e-Sevai centre or submitting an online application. "
        "This is <b>NOT</b> an official government certificate, acknowledgment receipt, or legal guarantee of eligibility or approval."
    )
    disclaimer_table = Table(
        [[Paragraph(disclaimer_text, disclaimer_style)]],
        colWidths=[515]
    )
    disclaimer_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EDF2F7")),
        ("BORDER", (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E0")),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    elements.append(disclaimer_table)
    elements.append(Spacer(1, 12))

    # 2. Metadata Information Block
    now_utc = datetime.now(timezone.utc).strftime("%d %B %Y, %H:%M UTC")
    verified_on = service_data.get("verification_date", "19 November 2026")
    source_url = service_data.get("source_url", "https://tnesevai.tn.gov.in")
    portal_name = service_data.get("portal_name", "Tamil Nadu e-Sevai (TNeGA)")

    # Published Timeline and Fee
    timeline_map = {
        "community-certificate": "Not specified on official portal",
        "nativity-certificate": "07 days (Published estimate; not a statutory guarantee)",
        "income-certificate": "15 days (Published estimate; not a statutory guarantee)",
    }
    timeline_text = timeline_map.get(service_slug, "Not specified on official portal")
    fee_text = "INR 60 (e-Sevai centre charge) + INR 0 (Department fee)"

    meta_data = [
        [
            Paragraph("<b>Official Portal:</b>", body_style),
            Paragraph(f"{portal_name}", body_style),
            Paragraph("<b>Generated On:</b>", body_style),
            Paragraph(f"{now_utc}", body_style),
        ],
        [
            Paragraph("<b>Source URL:</b>", body_style),
            Paragraph(f"{source_url}", body_style),
            Paragraph("<b>Verified On:</b>", body_style),
            Paragraph(f"{verified_on}", body_style),
        ],
        [
            Paragraph("<b>Statutory Fee:</b>", body_style),
            Paragraph(f"{fee_text}", body_style),
            Paragraph("<b>Estimated Timeline:</b>", body_style),
            Paragraph(f"{timeline_text}", body_style),
        ],
    ]
    meta_table = Table(meta_data, colWidths=[95, 175, 105, 140])
    meta_table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 12))

    # 3. Preparation Status Banner
    readiness_pct = progress_data.get("readiness_percentage", 0.0)
    is_accepting = progress_data.get("is_accepting", False)
    stage = progress_data.get("readiness_stage", "not_started")

    stage_labels = {
        "not_started": "No Applicability Decisions Made",
        "undetermined": "Applicability Decisions Pending",
        "in_progress": "Preparation In Progress",
        "complete": "Preparation Checklist Complete",
    }
    stage_text = stage_labels.get(stage, "Preparation In Progress")
    banner_bg = success_bg if is_accepting else warning_bg
    banner_color = success_color if is_accepting else warning_color

    status_p = Paragraph(
        f"<b>Status:</b> {stage_text} &nbsp;|&nbsp; <b>Readiness:</b> {readiness_pct}%",
        ParagraphStyle("Banner", parent=body_bold, fontSize=11, textColor=banner_color)
    )
    banner_table = Table([[status_p]], colWidths=[515])
    banner_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), banner_bg),
        ("BORDER", (0, 0), (-1, -1), 1.5, banner_color),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
    ]))
    elements.append(banner_table)
    elements.append(Spacer(1, 14))

    # 4. Group Requirements by Citizen Applicability and Completion
    app_completed = []
    app_pending = []
    undetermined_list = []
    not_app_list = []

    for req in requirements_data:
        app = req.get("applicability", "undetermined")
        is_comp = bool(req.get("is_completed", 0))

        if app == "applicable":
            if is_comp:
                app_completed.append(req)
            else:
                app_pending.append(req)
        elif app == "not_applicable":
            not_app_list.append(req)
        else:
            undetermined_list.append(req)

    def render_req_table(req_list: List[Dict[str, Any]], status_label: str, status_color: colors.Color) -> Table:
        rows = [
            [
                Paragraph("<b>#</b>", body_bold),
                Paragraph("<b>Document Requirement</b>", body_bold),
                Paragraph("<b>Official Classification</b>", body_bold),
                Paragraph("<b>Citizen Status</b>", body_bold),
            ]
        ]
        for idx, r in enumerate(req_list, 1):
            title = r.get("title", "")
            cat = r.get("presentation_category", "listed_applicability_unconfirmed")
            cat_display = {
                "listed_applicability_unconfirmed": "TNeGA Listed (Applicability Unconfirmed)",
                "alternative_option": "Official Alternative Option",
                "core_mandatory": "Statutory Mandatory",
            }.get(cat, "Listed")

            help_txt = r.get("help_text", "")
            doc_desc = f"<b>{title}</b>"
            if help_txt:
                doc_desc += f"<br/><font color='#718096' size='7.5'>{help_txt}</font>"

            # Alternative detail if selected
            alt_sel = r.get("selected_alternative")
            if alt_sel:
                doc_desc += f"<br/><font color='#2B6CB0' size='8'>Selected Alternative: {alt_sel}</font>"

            rows.append([
                Paragraph(str(idx), body_style),
                Paragraph(doc_desc, body_style),
                Paragraph(cat_display, body_style),
                Paragraph(f"<font color='{status_color}'><b>{status_label}</b></font>", body_style),
            ])

        t = Table(rows, colWidths=[25, 230, 160, 100])
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EDF2F7")),
            ("BORDER", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E0")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("PADDING", (0, 0), (-1, -1), 5),
        ]))
        return t

    # Section 1: Applicable & Prepared
    elements.append(Paragraph("1. Applicable Documents Prepared (Completed)", h2_style))
    if app_completed:
        elements.append(render_req_table(app_completed, "Prepared [YES]", colors.HexColor("#276749")))
    else:
        elements.append(Paragraph("<i>No applicable documents marked prepared yet.</i>", body_style))
    elements.append(Spacer(1, 10))

    # Section 2: Applicable & Awaiting Preparation
    elements.append(Paragraph("2. Applicable Documents Awaiting Preparation", h2_style))
    if app_pending:
        elements.append(render_req_table(app_pending, "Awaiting [PENDING]", colors.HexColor("#C53030")))
    else:
        elements.append(Paragraph("<i>No applicable documents currently pending.</i>", body_style))
    elements.append(Spacer(1, 10))

    # Section 3: Undetermined Applicability Decisions
    if undetermined_list:
        elements.append(Paragraph("3. Documents Awaiting Citizen Decision (Undetermined)", h2_style))
        elements.append(render_req_table(undetermined_list, "Decide (App/Not App)", colors.HexColor("#D69E2E")))
        elements.append(Spacer(1, 10))

    # Section 4: Citizen-Selected Not Applicable
    if not_app_list:
        elements.append(Paragraph("4. Documents Marked Not Applicable by Citizen", h2_style))
        elements.append(render_req_table(not_app_list, "Not Applicable", colors.HexColor("#718096")))
        elements.append(Spacer(1, 10))

    # Nativity Composite Rule Note
    if service_slug == "nativity-certificate":
        nativity_note = (
            "<b>Nativity Alternative Proof Rule:</b> Official TNeGA regulations specify 5-year residence evidence "
            "as a single composite requirement satisfied by <i>any one</i> of three alternatives: "
            "(1) School Education Certificate, (2) Employment Details, or (3) Proof for continuous residence in Tamil Nadu for 5 years. "
            "You only need to prepare one valid alternative."
        )
        nat_box = Table([[Paragraph(nativity_note, body_style)]], colWidths=[515])
        nat_box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EBF8FF")),
            ("BORDER", (0, 0), (-1, -1), 1, colors.HexColor("#BEE3F8")),
            ("PADDING", (0, 0), (-1, -1), 8),
        ]))
        elements.append(Spacer(1, 6))
        elements.append(nat_box)
        elements.append(Spacer(1, 12))

    # Bottom Footer Note
    footer_text = (
        "SevaPath is an independent citizen preparation assistant for Tamil Nadu public services. "
        "Generated without collecting Aadhaar numbers or government account credentials. "
        "Visit https://tnesevai.tn.gov.in for official online e-Sevai portal submissions."
    )
    elements.append(Spacer(1, 10))
    elements.append(HRFlowable(width="100%", thickness=0.5, color=muted_text, spaceBefore=4, spaceAfter=8))
    elements.append(Paragraph(footer_text, disclaimer_style))

    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
